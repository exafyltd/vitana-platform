#!/usr/bin/env node
// VTID-05803: generates infra/gitlab-engineering/ci/vtid-05803-load-stages.gitlab-ci.yml, the CI runner for the stages
// around the DMS full load. It runs on the existing authorized staging execution path, the same one as Kiro 5's
// acceptance job: GitLab OIDC -> $AWS_STAGING_ROLE_ARN, then ONE one-shot Fargate task of the existing family
// vitana-aurora-staging-migrate (env PGHOST = staging writer, secrets PGUSER/PGPASSWORD = staging master) with a command
// override.
// Each stage's files are embedded as a deterministic tar.xz in base64, checked against their sha256 inside the
// container, and run with the package's own runner (load-stages.sh: staging-writer gate, psql --single-transaction).
// The payload therefore always equals the files of this commit, and the generator test checks that. No new AWS
// resource, task revision, role or secret.
//   node scripts/aws/staging-db-load-stage-ci.mjs [--check]   (--check: exit 1 when the committed YAML is stale)
import { execFileSync } from 'node:child_process';
import crypto from 'node:crypto';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..', '..');
export const OUT_FILE = path.join(ROOT, 'infra/gitlab-engineering/ci/vtid-05803-load-stages.gitlab-ci.yml');
const RUNNER = 'docs/validation/VTID-05803/schema-restore-package/load-stages.sh';
export const STAGES = {
  probe: ['scripts/aws/staging-db-load-probe.sql'],
  'pre-load': ['scripts/aws/staging-db-vector-preload.sql'],
  'post-load-1': ['scripts/aws/staging-db-vector-postload.sql'],
  'post-load-2': ['scripts/aws/staging-db-restore-saved.sql'],
  report: ['scripts/aws/staging-db-vector-report.sql'],
};
export const OVERRIDE_LIMIT = 8192;

/** A file as it goes into the payload: whole-line comments removed (SQL `--`, shell `#` except the shebang), nothing
 *  else changed. ECS caps the whole override at 8192 bytes; the statements are byte-identical to the repository. */
export function strip(rel) {
  const text = fs.readFileSync(path.join(ROOT, rel), 'utf8');
  const sql = rel.endsWith('.sql');
  return text.split('\n').filter((l, i) => (sql ? !/^--/.test(l) || /^-- ;;$/.test(l) : !(/^\s*#/.test(l) && !(i === 0 && l.startsWith('#!'))))).join('\n');
}

/** Deterministic tar.xz of the runner plus one stage's files (comment-stripped): { b64, sha256 (of the tar.xz) }. */
export function payload(stage) {
  const files = [RUNNER, ...STAGES[stage]];
  const dir = fs.mkdtempSync(path.join(os.tmpdir(), 'lsp-'));
  for (const f of files) { fs.mkdirSync(path.dirname(path.join(dir, 't', f)), { recursive: true }); fs.writeFileSync(path.join(dir, 't', f), strip(f)); }
  const tar = path.join(dir, 'p.tar');
  execFileSync('tar', ['--sort=name', '--mtime=@0', '--owner=0', '--group=0', '--numeric-owner', '--mode=u=rwX,go=rX', '-C', path.join(dir, 't'), '-cf', tar, ...files]);
  const xz = execFileSync('xz', ['-9e', '-c', tar]);
  fs.rmSync(dir, { recursive: true, force: true });
  return { b64: xz.toString('base64'), sha256: crypto.createHash('sha256').update(xz).digest('hex') };
}

// Container command (inside the override, so keep it short). $LP = payload, $LPS = its sha256, $STAGE, $OUT (S3 prefix).
export const CONTAINER_CMD = [
  'set -u',
  'apt-get update -qq && apt-get install -y -qq --no-install-recommends postgresql-client awscli python3 ca-certificates xz-utils >/dev/null || exit 20',
  'mkdir -p /w && cd /w || exit 20',
  'printf %s "$LP" | base64 -d > p.txz || exit 21',
  'echo "$LPS  p.txz" | sha256sum -c - >/dev/null || exit 22',
  'xz -dc p.txz | tar -xf - || exit 21',
  'export STAGING_PGURI="postgresql://$(python3 -c "import os,urllib.parse as u;print(u.quote(os.environ[\'PGUSER\'],safe=\'\')+\':\'+u.quote(os.environ[\'PGPASSWORD\'],safe=\'\'))")@$PGHOST:${PGPORT:-5432}/vitana?sslmode=require" || exit 20',
  `bash ${RUNNER} > out.txt 2>&1; rc=$?; cat out.txt`,
  `f=docs/validation/VTID-05803/schema-restore-package/load-report.out; [ -f $f ] && cat $f >> out.txt`,
  'aws s3 cp out.txt "$OUT/$STAGE.txt" --only-show-errors || { [ $rc = 0 ] && exit 80; }',
  'exit $rc',
].join('; ');

export function render() {
  const P = Object.fromEntries(Object.keys(STAGES).map((s) => [s, payload(s)]));
  const vars = Object.entries(P).map(([s, p]) => `    LP_${s.replace(/-/g, '_')}: "${p.b64}"\n    LPS_${s.replace(/-/g, '_')}: "${p.sha256}"`).join('\n');
  const stages = Object.keys(STAGES).join('|');
  return `# GENERATED by scripts/aws/staging-db-load-stage-ci.mjs from this commit's files; do not edit by hand.
# VTID-05803 (Kiro 2, MR !69): the stages around the DMS full load on vitana-aurora-staging, on the existing authorized
# staging execution path (same as vtid-05803-acceptance-run): GitLab OIDC -> $AWS_STAGING_ROLE_ARN, one one-shot Fargate
# task of the existing family vitana-aurora-staging-migrate with a command override.
# Runs ONLY on main, in an api/web pipeline, with VTID05803_LOAD_STAGE set to one of: ${stages}.
#   probe       read-only; which stage the database is ready for (exit 10 = Path A schema restore not done yet)
#   pre-load    after Path A, BEFORE the DMS full load (staging-db-vector-preload.sql)
#   post-load-1 AFTER the DMS full load (staging-db-vector-postload.sql)
#   post-load-2 after post-load-1 (staging-db-restore-saved.sql)
#   report      read-only (staging-db-vector-report.sql)
# Every SQL stage is one transaction (psql --single-transaction, ON_ERROR_STOP) and idempotent. The target gate is
# load-stages.sh's: the exact staging writer, database vitana; production hosts are refused before psql runs.
# Exit contract: 0 stage done; 10 probe says the restore is not there yet; 1 refused; 2 SQL failed (rolled back);
# 3 configuration or infrastructure error. Output goes to s3://vitana-code-index/vtid-05803/staging/runs/<RUN>/<stage>.txt
# and to the log group /vitana/schema-parity.
vtid-05803-load-stage:
  stage: verify
  needs: []
  tags: [vitana-eng-v1]
  image: public.ecr.aws/docker/library/alpine:3.20
  interruptible: false
  retry: 0
  timeout: 90m
  id_tokens:
    GITLAB_OIDC_TOKEN:
      aud: https://sts.amazonaws.com
  variables:
    AWS_REGION: eu-central-1
    AWS_DEFAULT_REGION: eu-central-1
    AWS_ROLE_ARN: $AWS_STAGING_ROLE_ARN
    AWS_WEB_IDENTITY_TOKEN_FILE: /tmp/oidc-token
    CLUSTER: Vitana-ECS-Cluster
    NET_FROM_SERVICE: vitana-postgrest-aurora-proxy
    LS_TD: vitana-aurora-staging-migrate:2
${vars}
  rules:
    - if: $CI_COMMIT_BRANCH == "main" && $CI_PIPELINE_SOURCE =~ /^(api|web)$/ && $VTID05803_LOAD_STAGE =~ /^(${stages})$/
  artifacts:
    when: always
    expire_in: 90 days
    paths: [load-stage/]
  script:
    - |
      set -uo pipefail
      mkdir -p load-stage; A=load-stage; STAGE="$VTID05803_LOAD_STAGE"
      fin() {
        jq -n --argjson rc "$1" --arg r "$2" --arg stage "$STAGE" --arg run "\${RUN:-}" --arg task "\${TASK:-}" --arg out "\${OUT:-}" \\
          --arg ec "\${EXIT:-}" --arg sr "\${STOPPED:-}" --arg ls "\${LOGSTREAM:-}" --arg commit "$CI_COMMIT_SHA" --arg td "$LS_TD" \\
          '{vtid:"VTID-05803",step:"aurora-staging-load-stage",stage:$stage,exit_code:$rc,reason:$r,run:$run,task_definition:$td,task:$task,
            container_exit_code:$ec,stopped_reason:$sr,evidence_s3:$out,log_group:"/vitana/schema-parity",log_stream:$ls,platform_commit:$commit}' > "$A/result.json"
        cat "$A/result.json"; echo "LOAD STAGE RESULT stage=$STAGE exit=$1 $2"; exit "$1"
      }
      apk add --no-cache aws-cli jq >/dev/null || fin 3 "tool install failed"
      printf '%s' "$GITLAB_OIDC_TOKEN" > "$AWS_WEB_IDENTITY_TOKEN_FILE"
      [ "$(aws sts get-caller-identity --query Account --output text)" = 472838866351 ] || fin 3 "not account 472838866351"
      K=$(printf '%s' "$STAGE" | tr '-' '_'); eval "LP=\\\${LP_$K:-}; LPS=\\\${LPS_$K:-}"
      [ -n "$LP" ] && [ -n "$LPS" ] || fin 3 "no payload for stage $STAGE"
      case "$LS_TD" in vitana-aurora-staging-migrate:[0-9]*) ;; *) fin 3 "LS_TD must be a vitana-aurora-staging-migrate revision" ;; esac
      aws ecs describe-task-definition --task-definition "$LS_TD" --query taskDefinition > "$A/td.json" 2> "$A/td.err" || fin 3 "describe $LS_TD failed"
      CNAME=$(jq -r '.containerDefinitions[0].name' "$A/td.json")
      PGH=$(jq -r '.containerDefinitions[0].environment[]? | select(.name=="PGHOST") | .value' "$A/td.json")
      case "$PGH" in *prod*) fin 3 "task definition PGHOST names production" ;; vitana-aurora-staging.*) ;; *) fin 3 "task definition PGHOST is not the staging writer" ;; esac
      for s in PGUSER PGPASSWORD; do jq -e --arg s "$s" '.containerDefinitions[0].secrets[]? | select(.name==$s)' "$A/td.json" >/dev/null || fin 3 "task definition lacks secret $s"; done
      SVC=$(aws ecs describe-services --cluster "$CLUSTER" --services "$NET_FROM_SERVICE" --query 'services[0]' --output json) || fin 3 "describe $NET_FROM_SERVICE failed"
      case "$(printf '%s' "$SVC" | jq -r .taskDefinition)" in *staging*) ;; *) fin 3 "$NET_FROM_SERVICE does not run a staging task definition" ;; esac
      NET=$(printf '%s' "$SVC" | jq -c '{awsvpcConfiguration: (.networkConfiguration.awsvpcConfiguration | .assignPublicIp = "DISABLED")}')
      RUN=$(date -u +%Y%m%dT%H%M%SZ)-k2-load-$STAGE
      OUT=s3://vitana-code-index/vtid-05803/staging/runs/$RUN
      CMD=$(jq -cn --arg c '${CONTAINER_CMD.replace(/'/g, "'\"'\"'")}' '["bash","-c",$c]')
      jq -n --arg c "$CNAME" --argjson cmd "$CMD" --arg lp "$LP" --arg lps "$LPS" --arg st "$STAGE" --arg out "$OUT" \\
        '{containerOverrides: [{name: $c, command: $cmd, environment: [{name: "LP", value: $lp}, {name: "LPS", value: $lps}, {name: "STAGE", value: $st}, {name: "OUT", value: $out}]}]}' > "$A/overrides.json"
      OVB=$(wc -c < "$A/overrides.json"); echo "override bytes: $OVB (ECS limit ${OVERRIDE_LIMIT})"; [ "$OVB" -lt ${OVERRIDE_LIMIT} ] || fin 3 "override too large ($OVB bytes)"
      echo "run $RUN: stage $STAGE on $LS_TD (PGHOST $PGH), evidence $OUT/"
      aws ecs run-task --cluster "$CLUSTER" --task-definition "$LS_TD" --launch-type FARGATE --count 1 --network-configuration "$NET" \\
        --overrides "file://$A/overrides.json" --started-by "kiro2-load-$CI_JOB_ID" > "$A/run-task.json" 2> "$A/run-task.err" \\
        || fin 3 "run-task refused: $(tr '\\n' ' ' < "$A/run-task.err" | cut -c1-400)"
      TASK=$(jq -r '.tasks[0].taskArn // empty' "$A/run-task.json"); [ -n "$TASK" ] || fin 3 "run-task started no task: $(jq -c .failures "$A/run-task.json")"
      LOGSTREAM="staging-migrate/$CNAME/\${TASK##*/}"; echo "task $TASK, log /vitana/schema-parity $LOGSTREAM"
      for i in $(seq 1 160); do
        ST=$(aws ecs describe-tasks --cluster "$CLUSTER" --tasks "$TASK" --query 'tasks[0].lastStatus' --output text 2>/dev/null || echo UNKNOWN)
        [ "$ST" = STOPPED ] && break; [ $((i % 4)) -eq 0 ] && echo "  $(date -u +%H:%M:%S) $ST"; sleep 30
      done
      aws ecs describe-tasks --cluster "$CLUSTER" --tasks "$TASK" > "$A/describe-task.json" 2>/dev/null || fin 3 "describe-tasks failed"
      ST=$(jq -r '.tasks[0].lastStatus' "$A/describe-task.json"); STOPPED=$(jq -r '.tasks[0].stoppedReason // ""' "$A/describe-task.json")
      EXIT=$(jq -r '.tasks[0].containers[0].exitCode // ""' "$A/describe-task.json")
      echo "lastStatus=$ST exitCode=\${EXIT:-none} stoppedReason=$STOPPED"
      [ "$ST" = STOPPED ] || fin 3 "task did not reach STOPPED within 80 minutes"
      case "$EXIT" in
        0) fin 0 "stage $STAGE done; output $OUT/$STAGE.txt" ;;
        10) fin 10 "probe: the restored schema is not on staging yet (run Path A first); output $OUT/$STAGE.txt" ;;
        1) fin 1 "refused by the staging-writer gate; nothing written" ;;
        2) fin 2 "SQL failed and was rolled back; output $OUT/$STAGE.txt" ;;
        20|21|22) fin 3 "container setup or payload check failed (code $EXIT)" ;;
        80) fin 3 "stage ran but the output upload failed" ;;
        *) fin 3 "container exit \${EXIT:-none}: $STOPPED" ;;
      esac
`;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const text = render();
  if (process.argv.includes('--check')) {
    const cur = fs.existsSync(OUT_FILE) ? fs.readFileSync(OUT_FILE, 'utf8') : '';
    if (cur !== text) { console.error(`stale: ${path.relative(ROOT, OUT_FILE)} (run node scripts/aws/staging-db-load-stage-ci.mjs)`); process.exit(1); }
    console.log('up to date');
  } else {
    fs.writeFileSync(OUT_FILE, text);
    console.log(`wrote ${path.relative(ROOT, OUT_FILE)}`);
  }
}
