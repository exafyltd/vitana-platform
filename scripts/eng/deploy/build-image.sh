#!/bin/sh
# build-image.sh — build one service image with rootless BuildKit into an OCI archive (plan agentic-delivery §3.6
# step 2, `.build-image`, main class; VTID-05546). No push, no Docker daemon, no AWS: the deploy class pushes the
# archive (push-image.mjs).
#
# Runs in moby/buildkit:<version>-rootless as its unprivileged user, with BUILDKITD_FLAGS=--oci-worker-no-process-sandbox.
# With BUILDKIT_HOST set (the `.build-image` job: the daemon is its service, started with that flag) it is only the
# daemon's client; the main runner block gives service containers seccomp and AppArmor unconfined, never `privileged`
# (plan R5), and the job container keeps both profiles. Without BUILDKIT_HOST it starts its own daemon
# (buildctl-daemonless.sh), which needs the same two options for the job container itself.
#
# USAGE:
#   build-image.sh --context <dir> --dockerfile <path> --out <image.oci.tar> [--build-arg KEY=VALUE]...
#                  [--cache-dir <dir>] [--vite-staging-env <commit sha>]
#   --cache-dir         BuildKit layer cache (type=local) kept in the runner's S3 cache between jobs.
#   --vite-staging-env  vitana-v1 only: write <context>/.env.production for the staging gateway, as
#                       vitana-v1/.github/workflows/AWS-STAGE-DEPLOY-FRONTEND.yml does before its build.
set -eu

CONTEXT=""
DOCKERFILE=""
OUT=""
CACHE_DIR=""
VITE_SHA=""
BUILD_ARGS=""

usage() { sed -n '2,17p' "$0" | sed 's/^# \{0,1\}//'; }

while [ $# -gt 0 ]; do
  case "$1" in
    --context) CONTEXT="${2:?}"; shift 2 ;;
    --dockerfile) DOCKERFILE="${2:?}"; shift 2 ;;
    --out) OUT="${2:?}"; shift 2 ;;
    --cache-dir) CACHE_DIR="${2:?}"; shift 2 ;;
    --vite-staging-env) VITE_SHA="${2:?}"; shift 2 ;;
    --build-arg)
      case "${2:-}" in [A-Za-z_]*=*) ;; *) echo "--build-arg needs KEY=VALUE" >&2; exit 2 ;; esac
      BUILD_ARGS="${BUILD_ARGS}${BUILD_ARGS:+
}$2"; shift 2 ;;
    -h|--help) usage; exit 0 ;;
    *) echo "unknown argument: $1" >&2; usage >&2; exit 2 ;;
  esac
done
[ -n "$CONTEXT" ] && [ -n "$DOCKERFILE" ] && [ -n "$OUT" ] || { usage >&2; exit 2; }
[ -d "$CONTEXT" ] || { echo "no build context: $CONTEXT" >&2; exit 2; }
[ -f "$DOCKERFILE" ] || { echo "no Dockerfile: $DOCKERFILE" >&2; exit 2; }

case " ${BUILDKITD_FLAGS:-} " in
  *" --oci-worker-no-process-sandbox "*) ;;
  *) echo "refusing: BUILDKITD_FLAGS must hold --oci-worker-no-process-sandbox (rootless BuildKit, no privileged container)" >&2; exit 2 ;;
esac
if [ "$(id -u)" = 0 ]; then echo "refusing: build as the rootless BuildKit user, never as root" >&2; exit 2; fi
if [ -n "${BUILDKIT_HOST:-}" ]; then
  case "$BUILDKIT_HOST" in tcp://*|unix://*) ;; *) echo "BUILDKIT_HOST must be tcp://<host>:<port> or unix://<path>" >&2; exit 2 ;; esac
  case "$BUILDKIT_HOST" in *[!A-Za-z0-9:/._-]*) echo "BUILDKIT_HOST has an unexpected form" >&2; exit 2 ;; esac
  command -v buildctl >/dev/null 2>&1 || { echo "buildctl not found: run in moby/buildkit:<version>-rootless" >&2; exit 3; }
  BUILDCTL="buildctl --addr $BUILDKIT_HOST"
  # The service starts with the job; wait until it answers (up to 2 minutes).
  n=0
  until $BUILDCTL debug workers >/dev/null 2>&1; do
    n=$((n + 1))
    [ "$n" -lt 60 ] || { echo "the BuildKit service at $BUILDKIT_HOST did not answer in 2 minutes" >&2; exit 3; }
    sleep 2
  done
else
  command -v buildctl-daemonless.sh >/dev/null 2>&1 || { echo "buildctl-daemonless.sh not found: run in moby/buildkit:<version>-rootless" >&2; exit 3; }
  BUILDCTL="buildctl-daemonless.sh"
fi

if [ -n "$VITE_SHA" ]; then
  case "$VITE_SHA" in *[!0-9a-f]*|"") echo "--vite-staging-env needs a commit sha" >&2; exit 2 ;; esac
  GATEWAY="https://preview-aws-gateway.vitanaland.com"
  {
    echo "# Generated by build-image.sh (GitLab .build-image) for the staging build; never committed."
    echo "VITE_GATEWAY_BASE=$GATEWAY"
    echo "VITE_GATEWAY_URL=$GATEWAY/api/v1"
    echo "VITE_APP_VERSION=$(printf '%s' "$VITE_SHA" | cut -c1-12)"
    echo "VITE_DATA_API_URL=${VITE_DATA_API_URL_STAGING:-}"
    echo "VITE_REALTIME_URL=${VITE_REALTIME_URL_STAGING:-}"
    echo "VITE_HEALTH_REAL_DATA=true"
  } > "$CONTEXT/.env.production"
  sed 's/=.*/=<value>/' "$CONTEXT/.env.production"
fi

DF_DIR="$(dirname "$DOCKERFILE")"
DF_NAME="$(basename "$DOCKERFILE")"
set -- build --progress=plain --frontend dockerfile.v0 \
  --local "context=$CONTEXT" --local "dockerfile=$DF_DIR" --opt "filename=$DF_NAME" \
  --opt platform=linux/amd64 --output "type=oci,dest=$OUT"
if [ -n "$BUILD_ARGS" ]; then
  OLD_IFS="$IFS"; IFS='
'
  for a in $BUILD_ARGS; do set -- "$@" --opt "build-arg:$a"; done
  IFS="$OLD_IFS"
fi
if [ -n "$CACHE_DIR" ]; then
  if [ -f "$CACHE_DIR/index.json" ]; then set -- "$@" --import-cache "type=local,src=$CACHE_DIR"; else echo "cold build: no layer cache at $CACHE_DIR"; fi
  set -- "$@" --export-cache "type=local,dest=$CACHE_DIR.new,mode=max"
fi

START="$(date +%s)"
$BUILDCTL "$@"
END="$(date +%s)"
if [ -n "$CACHE_DIR" ] && [ -d "$CACHE_DIR.new" ]; then rm -rf "$CACHE_DIR"; mv "$CACHE_DIR.new" "$CACHE_DIR"; fi
echo "built $OUT in $((END - START)) s; sha256 $(sha256sum "$OUT" | cut -d' ' -f1)"
