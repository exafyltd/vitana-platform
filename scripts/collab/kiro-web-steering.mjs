#!/usr/bin/env node
/**
 * kiro-web-steering — make a Kiro Web session load the Vitana repositories' steering (plan kiro-web-steering).
 *
 * Kiro Web's workspace root is the folder the repositories are cloned into (e.g. /projects/sandbox), and in practice
 * only `<workspace>/.kiro/steering/` was loaded there. The repos' own `.kiro/steering/*.md` use repo-relative
 * `#[[file:…]]` links and `fileMatchPattern` globs, which are resolved from the workspace root, so a plain copy would
 * point at nothing. This script mirrors every repo steering file into `<workspace>/.kiro/steering/<repo>--<name>.md`
 * with those paths prefixed by the repo folder, and adds one always-included file that inlines the Kiro Web pipeline
 * runbooks (`.kiro/pipeline/driver.md`, `common-rules.md`, `planning.md`). It writes nothing inside a repository and
 * deletes only files that carry its own marker.
 *
 *   node vitana-platform/scripts/collab/kiro-web-steering.mjs [--workspace <dir>] [--check] [--json]
 *
 * --check writes nothing and exits 1 on any problem: a generated file missing or out of date, a link that does not
 * resolve from the workspace root, or a linked file that itself contains `#[[file:]]` (recursive resolution is not
 * documented by Kiro, so it is reported instead of assumed).
 */
import fs from 'node:fs';
import path from 'node:path';
import { execFileSync } from 'node:child_process';
import { fileURLToPath } from 'node:url';

export const MARKER = '<!-- generated by vitana-platform/scripts/collab/kiro-web-steering.mjs';
export const REPOS = ['exafyltd/vitana-platform', 'exafyltd/vitana-v1'];
export const PLATFORM = 'exafyltd/vitana-platform';
export const DRIVER_FILE = 'kiro-web-driver.md';
export const DRIVER_LINKS = ['.kiro/pipeline/driver.md', '.kiro/pipeline/common-rules.md', '.kiro/pipeline/planning.md'];
const LINK_RE = /#\[\[file:([^\]]+)\]\]/g;
const FM_RE = /^---\r?\n([\s\S]*?)\r?\n---\r?\n?/;

function git(dir, args) {
  try {
    return execFileSync('git', ['-C', dir, ...args], { encoding: 'utf8', stdio: ['ignore', 'pipe', 'ignore'] }).trim();
  } catch {
    return '';
  }
}

/** `owner/name` of a checkout's origin, or '' (https, ssh and proxied URLs all end in owner/name[.git]). */
export function originSlug(dir) {
  const url = git(dir, ['remote', 'get-url', 'origin']);
  const m = /([^/:]+)\/([^/]+?)(?:\.git)?\/?$/.exec(url);
  return m ? `${m[1]}/${m[2]}` : '';
}

/** Vitana checkouts directly under the workspace that have `.kiro/steering/`, platform first. */
export function findRepos(workspace) {
  return scanRepos(workspace).repos;
}

/** Vitana checkouts under the workspace: `repos` (with `.kiro/steering/`) and `skipped` (a known one without it). */
export function scanRepos(workspace) {
  const repos = [];
  const skipped = [];
  for (const ent of fs.readdirSync(workspace, { withFileTypes: true })) {
    if (!ent.isDirectory() || ent.name.startsWith('.')) continue;
    const dir = path.join(workspace, ent.name);
    if (!fs.existsSync(path.join(dir, '.git'))) continue;
    const slug = originSlug(dir);
    if (!REPOS.includes(slug)) continue;
    if (!fs.existsSync(path.join(dir, '.kiro', 'steering'))) {
      skipped.push(`${ent.name} (${slug}): no .kiro/steering/`);
      continue;
    }
    repos.push({ prefix: ent.name, dir, slug, sha: git(dir, ['rev-parse', '--short', 'HEAD']) || 'unknown' });
  }
  repos.sort((a, b) => REPOS.indexOf(a.slug) - REPOS.indexOf(b.slug) || a.prefix.localeCompare(b.prefix));
  return { repos, skipped };
}

const posix = (p) => p.split(path.sep).join('/');
const prefixed = (prefix, p) => `${prefix}/${p.trim().replace(/^\.\//, '')}`;

/** Prefix every `fileMatchPattern` glob (scalar, inline list or block list); every other line is kept verbatim. */
export function rewriteFrontMatter(fm, prefix) {
  const out = [];
  let inList = false;
  for (const line of fm.split(/\r?\n/)) {
    const key = /^fileMatchPattern:\s*(.*)$/.exec(line);
    if (key) {
      const v = key[1].trim();
      inList = v === '';
      if (v.startsWith('[')) {
        const items = v.replace(/^\[|\]$/g, '').split(',').map((s) => s.trim()).filter(Boolean);
        out.push(`fileMatchPattern: [${items.map((s) => quoteLike(s, prefixed(prefix, unquote(s)))).join(', ')}]`);
      } else if (v) {
        out.push(`fileMatchPattern: ${quoteLike(v, prefixed(prefix, unquote(v)))}`);
      } else {
        out.push(line);
      }
      continue;
    }
    const item = inList ? /^(\s+-\s+)(.*)$/.exec(line) : null;
    if (item) {
      out.push(`${item[1]}${quoteLike(item[2].trim(), prefixed(prefix, unquote(item[2].trim())))}`);
      continue;
    }
    if (!/^\s/.test(line)) inList = false;
    out.push(line);
  }
  return out.join('\n');
}

function unquote(s) {
  return /^(["']).*\1$/.test(s) ? s.slice(1, -1) : s;
}
function quoteLike(orig, value) {
  const q = /^(["'])/.exec(orig);
  return q ? `${q[1]}${value}${q[1]}` : `"${value}"`;
}

export const rewriteLinks = (body, prefix) => body.replace(LINK_RE, (_, p) => `#[[file:${prefixed(prefix, p)}]]`);
export const linksOf = (text) => [...text.matchAll(LINK_RE)].map((m) => m[1].trim());

/** One generated steering file from a repo steering file's text. Front matter stays the first content. */
export function transform(text, { prefix, source, sha }) {
  const marker = `${MARKER} from ${prefix}/.kiro/steering/${source} @ ${sha}; do not edit -->`;
  const m = FM_RE.exec(text);
  if (!m) return `${marker}\n${rewriteLinks(text, prefix)}`;
  return `---\n${rewriteFrontMatter(m[1], prefix)}\n---\n${marker}\n${rewriteLinks(text.slice(m[0].length), prefix)}`;
}

export function driverFile(platform) {
  return [
    '---',
    'inclusion: always',
    '---',
    `${MARKER} from ${platform.prefix}/.kiro/pipeline @ ${platform.sha}; do not edit -->`,
    '# Kiro Web: the pipeline runbook of this session',
    '',
    `\`${platform.prefix}/.kiro/steering/vitana-pipeline.md\` names \`.kiro/pipeline/driver.md\` as the way a Kiro Web`,
    'session runs every owner task that results in a commit. Its text and the rules it binds are linked below so they',
    'are part of this session, not only named. Where they differ from the repository rule files, the rule files win',
    '(`common-rules.md` rule 2).',
    '',
    ...DRIVER_LINKS.map((l) => `#[[file:${prefixed(platform.prefix, l)}]]`),
    '',
  ].join('\n');
}

/** Everything the workspace steering folder should hold: Map(file name → content). */
export function plan(workspace) {
  const { repos, skipped } = scanRepos(workspace);
  const files = new Map();
  const seen = new Map(); // steering file name → platform text
  for (const repo of repos) {
    const dir = path.join(repo.dir, '.kiro', 'steering');
    for (const name of fs.readdirSync(dir).filter((f) => f.endsWith('.md')).sort()) {
      const text = fs.readFileSync(path.join(dir, name), 'utf8');
      if (repo.slug !== PLATFORM && seen.get(name) === text && linksOf(text).length === 0) continue;
      if (repo.slug === PLATFORM) seen.set(name, text);
      files.set(`${repo.prefix}--${name}`, transform(text, { prefix: repo.prefix, source: name, sha: repo.sha }));
    }
  }
  const platform = repos.find((r) => r.slug === PLATFORM);
  if (platform) files.set(`${platform.prefix}--${DRIVER_FILE}`, driverFile(platform));
  return { repos, skipped, files };
}

const isGenerated = (file) => {
  try {
    return fs.readFileSync(file, 'utf8').includes(MARKER);
  } catch {
    return false;
  }
};

/** Problems with the steering folder as it is now (nothing written). */
export function check(workspace, files) {
  const problems = [];
  const out = path.join(workspace, '.kiro', 'steering');
  for (const [name, content] of files) {
    const file = path.join(out, name);
    if (!fs.existsSync(file)) problems.push(`${name}: missing`);
    else if (fs.readFileSync(file, 'utf8') !== content) problems.push(`${name}: out of date`);
    for (const link of linksOf(content)) {
      const target = path.join(workspace, link);
      if (!fs.existsSync(target)) {
        problems.push(`${name}: #[[file:${link}]] does not resolve from ${posix(workspace)}`);
        continue;
      }
      const nested = linksOf(fs.readFileSync(target, 'utf8'));
      if (nested.length) problems.push(`${name}: ${link} itself links ${nested.join(', ')} (nested links are not resolved)`);
    }
  }
  if (fs.existsSync(out)) {
    for (const f of fs.readdirSync(out)) {
      if (!files.has(f) && isGenerated(path.join(out, f))) problems.push(`${f}: stale generated file`);
    }
  }
  return problems;
}

/** Write the steering set and remove stale generated files. Returns { written, removed }. */
export function write(workspace, files) {
  const out = path.join(workspace, '.kiro', 'steering');
  fs.mkdirSync(out, { recursive: true });
  const written = [];
  const removed = [];
  for (const [name, content] of files) {
    const file = path.join(out, name);
    if (!fs.existsSync(file) || fs.readFileSync(file, 'utf8') !== content) {
      fs.writeFileSync(file, content);
      written.push(name);
    }
  }
  for (const f of fs.readdirSync(out)) {
    if (!files.has(f) && isGenerated(path.join(out, f))) {
      fs.rmSync(path.join(out, f));
      removed.push(f);
    }
  }
  return { written, removed };
}

/** Bytes of every always-included generated file with its links inlined (no front matter = Kiro's default, always). */
export function alwaysBytes(workspace, files) {
  let total = 0;
  for (const content of files.values()) {
    const m = FM_RE.exec(content);
    const inclusion = m ? (/^inclusion:\s*(\S+)/m.exec(m[1]) || [])[1] : undefined;
    if (inclusion && inclusion !== 'always') continue;
    total += Buffer.byteLength(content);
    for (const link of linksOf(content)) {
      const target = path.join(workspace, link);
      if (fs.existsSync(target)) total += fs.statSync(target).size;
    }
  }
  return total;
}

export function defaultWorkspace() {
  const here = path.dirname(fileURLToPath(import.meta.url));
  const top = git(here, ['rev-parse', '--show-toplevel']) || path.resolve(here, '..', '..');
  // A lane worktree (<repo>/.worktrees/<name>) still belongs to the main checkout's workspace.
  const common = git(here, ['rev-parse', '--path-format=absolute', '--git-common-dir']);
  const repoRoot = common ? path.dirname(common) : top;
  return path.dirname(repoRoot);
}

export function main(argv) {
  const args = argv.slice(2);
  const opt = (k) => {
    const i = args.indexOf(k);
    return i >= 0 ? args[i + 1] : undefined;
  };
  const workspace = path.resolve(opt('--workspace') || defaultWorkspace());
  const { repos, skipped, files } = plan(workspace);
  if (repos.length === 0) {
    console.error(`kiro-web-steering: no Vitana checkout with .kiro/steering under ${workspace}`);
    return 1;
  }
  let result = {};
  if (!args.includes('--check')) result = write(workspace, files);
  const problems = check(workspace, files);
  const out = path.join(workspace, '.kiro', 'steering');
  const list = [...files.keys()].map((n) => ({ file: n, bytes: Buffer.byteLength(files.get(n)) }));
  const always = alwaysBytes(workspace, files);
  if (args.includes('--json')) {
    console.log(JSON.stringify({ workspace, repos: repos.map((r) => `${r.prefix}=${r.slug}@${r.sha}`), files: list, always_bytes: always, skipped, ...result, problems }));
  } else {
    console.log(`kiro-web-steering: ${posix(out)} (${repos.map((r) => `${r.prefix}@${r.sha}`).join(', ')})`);
    for (const f of list) console.log(`  ${f.file} ${f.bytes} B`);
    for (const k of skipped) console.log(`  skipped ${k}`);
    console.log(`  always-included, links inlined: ${always} B (Kiro may truncate a long inlined link; see docs/kiro/kiro-web-bootstrap.md)`);
    if (result.written) console.log(`  written ${result.written.length}, removed ${result.removed.length}`);
    for (const p of problems) console.log(`PROBLEM ${p}`);
    console.log(problems.length ? `kiro-web-steering: ${problems.length} problem(s)` : 'kiro-web-steering: ok');
  }
  return problems.length ? 1 : 0;
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) process.exitCode = main(process.argv);
