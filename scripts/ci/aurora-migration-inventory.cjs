#!/usr/bin/env node
/**
 * VTID-03494 — inventory the Supabase surface that a full platform replacement
 * (Option B: Aurora + non-Supabase auth/realtime/storage) has to replace.
 *
 * "2,550 call sites" is a number, not a plan. This turns it into a worklist:
 * which tables, which RPCs, which files, ranked by how much of each is
 * concentrated where — so the migration can be sequenced by subsystem instead
 * of attempted big-bang.
 *
 * Deliberately dependency-free and read-only. Run:
 *   node scripts/ci/aurora-migration-inventory.cjs            # markdown summary
 *   node scripts/ci/aurora-migration-inventory.cjs --json     # full data
 *
 * KNOWN IMPRECISION — read before quoting these numbers.
 * The `from` pattern matches `.from('x')` textually, so it also catches
 * `.storage.from('avatars')` (a bucket, not a table) and any unrelated
 * `.from()` on a non-Supabase builder. Cross-referencing `from` keys against
 * the live schema will therefore show some names that are buckets, views, or
 * local variables rather than missing tables. Spot-check before acting on an
 * individual entry; the aggregate is still the right order of magnitude for
 * sequencing work.
 */

const { readdirSync, readFileSync, statSync } = require('node:fs');
const { join, relative } = require('node:path');

const REPO_ROOT = join(__dirname, '..', '..');

// Roots to scan. vitana-v1 is a sibling checkout; skipped when absent.
const ROOTS = [
  { label: 'gateway', dir: join(REPO_ROOT, 'services') },
  { label: 'frontend', dir: join(REPO_ROOT, '..', 'vitana-v1', 'src') },
];

const SKIP_DIR = /(^|\/)(node_modules|dist|build|coverage|\.git)(\/|$)/;

function walk(dir, out = []) {
  let entries;
  try {
    entries = readdirSync(dir);
  } catch {
    return out;
  }
  for (const e of entries) {
    const p = join(dir, e);
    if (SKIP_DIR.test(p)) continue;
    let st;
    try {
      st = statSync(p);
    } catch {
      continue;
    }
    if (st.isDirectory()) walk(p, out);
    else if (/\.(ts|tsx|js|jsx)$/.test(e)) out.push(p);
  }
  return out;
}

const PATTERNS = {
  // The data API — the bulk of the work. PostgREST has no Aurora equivalent.
  from: /\.from\(\s*['"`]([a-zA-Z0-9_]+)['"`]/g,
  rpc: /\.rpc\(\s*['"`]([a-zA-Z0-9_]+)['"`]/g,
  // GoTrue — must be replaced wholesale (Cognito or self-issued JWT).
  auth: /\.auth\.([a-zA-Z]+)\s*\(/g,
  // Realtime — replaced by WebSockets we own.
  realtime: /\.channel\(\s*['"`]([^'"`]*)['"`]/g,
  // Storage — S3, different API shape.
  storage: /\.storage\.from\(\s*['"`]([^'"`]*)['"`]/g,
};

function tally(map, key, file) {
  if (!map[key]) map[key] = { count: 0, files: new Set() };
  map[key].count += 1;
  map[key].files.add(file);
}

function scan() {
  const result = {};
  for (const { label, dir } of ROOTS) {
    const files = walk(dir);
    const acc = {
      files_scanned: files.length,
      files_importing_supabase: 0,
      from: {},
      rpc: {},
      auth: {},
      realtime: {},
      storage: {},
      by_file: {},
    };
    for (const f of files) {
      let src;
      try {
        src = readFileSync(f, 'utf8');
      } catch {
        continue;
      }
      const rel = relative(REPO_ROOT, f);
      if (/@supabase\/supabase-js|integrations\/supabase|lib\/supabase/.test(src)) {
        acc.files_importing_supabase += 1;
      }
      let fileHits = 0;
      for (const [kind, re] of Object.entries(PATTERNS)) {
        re.lastIndex = 0;
        let m;
        while ((m = re.exec(src)) !== null) {
          tally(acc[kind], m[1], rel);
          fileHits += 1;
        }
      }
      if (fileHits > 0) acc.by_file[rel] = fileHits;
    }
    result[label] = acc;
  }
  return result;
}

function top(map, n) {
  return Object.entries(map)
    .map(([k, v]) => ({ name: k, count: v.count, files: v.files.size }))
    .sort((a, b) => b.count - a.count)
    .slice(0, n);
}

function totals(map) {
  return Object.values(map).reduce((s, v) => s + v.count, 0);
}

function main() {
  const data = scan();
  const asJson = process.argv.includes('--json');

  if (asJson) {
    const plain = {};
    for (const [label, acc] of Object.entries(data)) {
      plain[label] = { ...acc };
      for (const kind of Object.keys(PATTERNS)) {
        plain[label][kind] = Object.fromEntries(
          Object.entries(acc[kind]).map(([k, v]) => [k, { count: v.count, files: [...v.files] }]),
        );
      }
    }
    console.log(JSON.stringify(plain, null, 2));
    return;
  }

  console.log('# Aurora migration surface inventory (VTID-03494)\n');
  console.log('Generated by scripts/ci/aurora-migration-inventory.cjs\n');

  for (const [label, acc] of Object.entries(data)) {
    if (acc.files_scanned === 0) {
      console.log(`## ${label}\n\n_not present in this checkout — skipped_\n`);
      continue;
    }
    console.log(`## ${label}\n`);
    console.log(`- files scanned: **${acc.files_scanned}**`);
    console.log(`- files touching supabase: **${acc.files_importing_supabase}**`);
    console.log(`- \`.from()\` calls: **${totals(acc.from)}** across **${Object.keys(acc.from).length}** tables`);
    console.log(`- \`.rpc()\` calls: **${totals(acc.rpc)}** across **${Object.keys(acc.rpc).length}** functions`);
    console.log(`- auth calls: **${totals(acc.auth)}**`);
    console.log(`- realtime channels: **${totals(acc.realtime)}**`);
    console.log(`- storage calls: **${totals(acc.storage)}**\n`);

    const heaviest = Object.entries(acc.by_file)
      .sort((a, b) => b[1] - a[1])
      .slice(0, 15);
    if (heaviest.length) {
      console.log(`### Heaviest files — migrate/abstract these first\n`);
      console.log('| file | supabase call sites |');
      console.log('|---|---|');
      for (const [f, n] of heaviest) console.log(`| \`${f}\` | ${n} |`);
      console.log('');
    }

    const t = top(acc.from, 15);
    if (t.length) {
      console.log(`### Most-referenced tables\n`);
      console.log('| table | calls | files |');
      console.log('|---|---|---|');
      for (const r of t) console.log(`| \`${r.name}\` | ${r.count} | ${r.files} |`);
      console.log('');
    }

    const r = top(acc.rpc, 15);
    if (r.length) {
      console.log(`### Most-used RPCs — each needs an Aurora-side equivalent\n`);
      console.log('| function | calls | files |');
      console.log('|---|---|---|');
      for (const x of r) console.log(`| \`${x.name}\` | ${x.count} | ${x.files} |`);
      console.log('');
    }

    const a = top(acc.auth, 20);
    if (a.length) {
      console.log(`### Auth methods in use — all need a GoTrue replacement\n`);
      console.log('| method | calls | files |');
      console.log('|---|---|---|');
      for (const x of a) console.log(`| \`auth.${x.name}()\` | ${x.count} | ${x.files} |`);
      console.log('');
    }
  }
}

if (require.main === module) main();

module.exports = { scan, walk, PATTERNS };
