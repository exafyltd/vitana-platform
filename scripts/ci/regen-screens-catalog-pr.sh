#!/usr/bin/env bash
# VTID-05080 — publish / clean up the ONE rolling screens-catalog PR.
#
# Called by .github/workflows/REGEN-SCREENS-CATALOG.yml:
#   regen-screens-catalog-pr.sh publish   # the regen produced a diff
#   regen-screens-catalog-pr.sh cleanup   # the regen produced no diff
#
# Why a script: the branch/lease/PR logic must be testable against a local
# bare repo and a fake `gh` (services/gateway/test/vtid-05080-*.test.ts).
#
# Inputs (env):
#   REGEN_STANDING_VTID   standing VTID named in the PR title (required)
#   SCREENS_CATALOG_PR_TOKEN  PAT that may start workflows (required for publish)
#   GITHUB_TOKEN          default token, used by cleanup only
#   GITHUB_REPOSITORY     owner/repo (publish builds the remote URL from it)
#   REGEN_REMOTE_URL      override of the push remote (tests)
#   REGEN_BRANCH / REGEN_BASE   default auto/screens-catalog / main
#
# Never enable `set -x` here: the remote URL carries the PAT.
set -euo pipefail

MODE="${1:?usage: regen-screens-catalog-pr.sh publish|cleanup}"
BRANCH="${REGEN_BRANCH:-auto/screens-catalog}"
BASE="${REGEN_BASE:-main}"
VTID="${REGEN_STANDING_VTID:?REGEN_STANDING_VTID is required}"
FILES=(
  services/gateway/specs/dev-screen-inventory-v1.json
  services/gateway/src/frontend/command-hub/navigation-config.js
)
TITLE="chore(screens): auto-regenerate catalog from sources (DEV-COMHU-0413) (${VTID})"

open_pr_count() {
  # Prints the number of open PRs on $BRANCH, or nothing if the API call fails.
  gh pr list --head "$BRANCH" --base "$BASE" --state open --json number --jq 'length' 2>/dev/null || true
}

publish() {
  if [ -z "${SCREENS_CATALOG_PR_TOKEN:-}" ]; then
    echo "::error::SCREENS_CATALOG_PR_TOKEN is not set. The catalog changed, but a PR opened with the default GITHUB_TOKEN would run no checks and could never merge. Create a fine-grained PAT or app token (contents + pull-requests write) and store it as the repository secret SCREENS_CATALOG_PR_TOKEN."
    exit 1
  fi

  local remote="${REGEN_REMOTE_URL:-https://x-access-token:${SCREENS_CATALOG_PR_TOKEN}@github.com/${GITHUB_REPOSITORY:?GITHUB_REPOSITORY is required}.git}"
  git remote set-url origin "$remote"

  git config user.name "screens-catalog-bot"
  git config user.email "screens-catalog-bot@users.noreply.github.com"
  git checkout -q -B "$BRANCH"
  git add "${FILES[@]}"
  git commit -q -m "chore(screens): auto-regenerate catalog from sources (DEV-COMHU-0413) (${VTID})"

  # ls-remote runs AFTER the credentialed remote is set. An absent branch gives
  # an empty sha, and `--force-with-lease=<ref>:` then means "must not exist".
  local lease
  lease="$(git ls-remote --heads origin "$BRANCH" | cut -f1)"
  git push -q --force-with-lease="${BRANCH}:${lease}" origin "HEAD:refs/heads/${BRANCH}"

  export GH_TOKEN="$SCREENS_CATALOG_PR_TOKEN"
  local open
  open="$(open_pr_count)"
  if [ "$open" = "0" ]; then
    local body
    body="Auto-generated by [REGEN-SCREENS-CATALOG](.github/workflows/REGEN-SCREENS-CATALOG.yml). Source: runtime \`NAVIGATION_CONFIG\` in app.js + \`ADMIN_SECTIONS\` in vitana-v1/src/config/admin-navigation.ts + \`screens-overrides.json\` sidecar. Rolling PR: later runs update this branch instead of opening new PRs. If this PR's only diff is the spec JSON / nav-config.js, no human review needed — auto-merge lands it once CI passes.

VTID: ${VTID}
VALIDATION_PROFILE: gateway_backend
SCOPE_ALLOWLIST: services/gateway/specs/dev-screen-inventory-v1.json, services/gateway/src/frontend/command-hub/navigation-config.js
ACCEPTANCE: docs/validation/${VTID}/acceptance.md
MERGE_PAYLOAD_PREVIEW: regenerated Command Hub screen catalog (spec JSON + navigation-config.js), no other files
OASIS_IMPACT: no
VTID_AUTO_CLOSE: no"
    gh pr create --base "$BASE" --head "$BRANCH" --title "$TITLE" --body "$body"
    gh pr merge --squash --auto "$BRANCH" \
      || echo "::warning::PR opened but auto-merge could not be enabled — merge it by hand"
  elif [ -z "$open" ]; then
    echo "::warning::could not list PRs for $BRANCH — the branch is pushed, check for an open PR by hand"
  else
    echo "PR for $BRANCH already open — it now carries this run's regenerated catalog."
  fi
}

cleanup() {
  export GH_TOKEN="${GITHUB_TOKEN:?GITHUB_TOKEN is required}"
  local open number
  open="$(open_pr_count)"
  if [ -z "$open" ] || [ "$open" = "0" ]; then
    echo "No open catalog PR to clean up."
    return 0
  fi
  number="$(gh pr list --head "$BRANCH" --base "$BASE" --state open --json number --jq '.[0].number')"
  gh pr close "$number" --delete-branch \
    --comment "Closing: the catalog already matches ${BASE}, so this rolling PR has nothing left to carry. The next catalog change opens a fresh one."
}

case "$MODE" in
  publish) publish ;;
  cleanup) cleanup ;;
  *) echo "unknown mode: $MODE" >&2; exit 2 ;;
esac
