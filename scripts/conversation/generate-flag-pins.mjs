#!/usr/bin/env node
/**
 * VTID-04525 (Conversation hub B7) — extract the env pins the two gateway
 * deploy workflows declare, for the conversation flag registry.
 *
 * Reads `{name:"X", value:"Y"}` entries (jq task-definition edits) from
 * AWS-STAGE-DEPLOY-GATEWAY.yml and AWS-PROD-DEPLOY-GATEWAY.yml and writes
 * services/gateway/src/services/conversation/conversation-flag-pins.generated.ts.
 * A value set from a shell variable (`value:$X`) is recorded as `dynamic`.
 * A name pinned more than once with different values records them all,
 * joined by " | ", so a conflict is visible instead of silently resolved.
 *
 *   node scripts/conversation/generate-flag-pins.mjs          # write
 *   node scripts/conversation/generate-flag-pins.mjs --check  # exit 1 if stale
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..', '..');
const WORKFLOWS = {
  staging: '.github/workflows/AWS-STAGE-DEPLOY-GATEWAY.yml',
  prod: '.github/workflows/AWS-PROD-DEPLOY-GATEWAY.yml',
};
const OUT = 'services/gateway/src/services/conversation/conversation-flag-pins.generated.ts';

const PIN_RE = /\{\s*"?name"?\s*:\s*"([A-Z0-9_]+)"\s*,\s*"?value"?\s*:\s*(?:"([^"]*)"|\$[A-Za-z_][A-Za-z0-9_]*)\s*\}/g;

export function extractPins(text) {
  const found = new Map();
  for (const m of text.matchAll(PIN_RE)) {
    const value = m[2] === undefined ? 'dynamic' : m[2];
    if (!found.has(m[1])) found.set(m[1], new Set());
    found.get(m[1]).add(value);
  }
  const out = {};
  for (const [name, values] of found) out[name] = [...values].join(' | ');
  return out;
}

export function render(root = ROOT) {
  const byStack = {};
  for (const [stack, rel] of Object.entries(WORKFLOWS)) byStack[stack] = extractPins(readFileSync(join(root, rel), 'utf8'));
  const names = [...new Set([...Object.keys(byStack.staging), ...Object.keys(byStack.prod)])].sort();
  const lines = names.map((n) => {
    const s = byStack.staging[n];
    const p = byStack.prod[n];
    return `  ${n}: { staging: ${s === undefined ? 'null' : JSON.stringify(s)}, prod: ${p === undefined ? 'null' : JSON.stringify(p)} },`;
  });
  return [
    '// GENERATED by scripts/conversation/generate-flag-pins.mjs — do not edit by hand.',
    '// Source: the `{name:"X", value:"Y"}` entries in AWS-STAGE-DEPLOY-GATEWAY.yml and',
    '// AWS-PROD-DEPLOY-GATEWAY.yml. `dynamic` = set from a shell variable at deploy time.',
    '// null = the workflow does not pin it (the task definition keeps whatever it had).',
    '// flow-test-exempt: a data mirror of the deploy workflows, regenerated whenever any',
    '// pinned env changes (most are not conversation flags); it holds no flow logic, and',
    '// test/services/conversation/vtid-04525-conversation-flag-registry.test.ts checks it',
    '// is current. The flags that DO change conversation behaviour are tested where used.',
    '',
    'export const GATEWAY_WORKFLOW_PINS: Record<string, { staging: string | null; prod: string | null }> = {',
    ...lines,
    '};',
    '',
  ].join('\n');
}

if (import.meta.url === `file://${process.argv[1]}`) {
  const next = render();
  const path = join(ROOT, OUT);
  if (process.argv.includes('--check')) {
    let cur = '';
    try { cur = readFileSync(path, 'utf8'); } catch { /* missing */ }
    if (cur !== next) {
      console.error(`${OUT} is stale — run: node scripts/conversation/generate-flag-pins.mjs`);
      process.exit(1);
    }
    console.log(`${OUT} is current.`);
  } else {
    writeFileSync(path, next);
    console.log(`wrote ${OUT}`);
  }
}
